import { useEffect, useState } from "react";
import "./App.css";
import { CameraTable } from "./components/CameraTable";
import { NetworkPanel } from "./components/NetworkPanel";
import { SummaryStrip } from "./components/SummaryStrip";
import type { InventoryReport } from "./types";

/**
 * Path to the report JSON this viewer loads. Defaults to the bundled
 * sample report generated from `examples/cameras.yaml`. To view a real
 * survey's output, replace `public/sample-report.json` with your own
 * `report.json` (or change this constant) -- see README.md.
 */
const REPORT_URL = "sample-report.json";

type LoadState =
  | { status: "loading" }
  | { status: "error"; message: string }
  | { status: "ready"; report: InventoryReport };

function App() {
  const [state, setState] = useState<LoadState>({ status: "loading" });

  useEffect(() => {
    let cancelled = false;

    fetch(REPORT_URL)
      .then((res) => {
        if (!res.ok) {
          throw new Error(`${res.status} ${res.statusText}`);
        }
        return res.json() as Promise<InventoryReport>;
      })
      .then((report) => {
        if (!cancelled) setState({ status: "ready", report });
      })
      .catch((err: unknown) => {
        if (!cancelled) {
          const message = err instanceof Error ? err.message : String(err);
          setState({ status: "error", message });
        }
      });

    return () => {
      cancelled = true;
    };
  }, []);

  return (
    <div className="page">
      <header className="page-header">
        <h1>Camera Network Discovery - Site Survey Report</h1>
        <p className="page-subtitle">
          Camera inventory, RTSP stream health, and network readiness results
          produced by <code>camtoolkit survey</code>.
        </p>
      </header>

      {state.status === "loading" && <p className="status-message">Loading report...</p>}

      {state.status === "error" && (
        <p className="status-message status-message-error">
          Could not load report data: {state.message}
        </p>
      )}

      {state.status === "ready" && (
        <>
          <section className="report-meta">
            <div>
              <span className="report-meta-label">Survey</span>
              <span className="report-meta-value">{state.report.survey_name}</span>
            </div>
            <div>
              <span className="report-meta-label">Generated</span>
              <span className="report-meta-value">
                {new Date(state.report.generated_at).toLocaleString()}
              </span>
            </div>
          </section>

          <SummaryStrip report={state.report} />

          <section>
            <h2>Camera inventory &amp; RTSP health</h2>
            <CameraTable cameras={state.report.cameras} />
          </section>

          <section>
            <h2>Network readiness</h2>
            <NetworkPanel cameras={state.report.cameras} />
          </section>
        </>
      )}

      <footer className="page-footer">
        Generated by the Camera Network Discovery Toolkit. This viewer reads
        the report's JSON output directly -- no live backend involved.
      </footer>
    </div>
  );
}

export default App;
